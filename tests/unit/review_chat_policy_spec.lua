local policy = require("parley.skills.review.chat_policy")
local structure = require("parley.skills.review.chat_structure")
local function scan(lines)
    local facts, err = structure.snapshot(lines)
    assert.is_nil(err)
    return policy.scan(lines, facts)
end
describe("chat policy", function()
    it("retains valid tags and distinguishes misplaced and literal tags", function()
        local result = scan({ "@@chat@@", "# Notes", "1. ask", "@@chat@@", "", "```", "@@chat@@", "```", "# End" })
        assert.same({ 1 }, result.tags)
        assert.same({ 4 }, result.misplaced)
        assert.same({ { heading = 2, finish = 8, source = "tag", legacy = false } }, result.sections)
    end)
    it("does not report standalone tag text inside multiline inline code", function()
        local result = scan({ "`", "@@chat@@", "`", "", "# Notes" })
        assert.same({}, result.misplaced)
    end)
    it("normalizes every matching heading and reports unmatched legacy names", function()
        local result = scan({ "---", "collaboration-mode: {chat: [NOTES, Missing]}", "---", "# Notes (first)", "- ask", "# notes", "- ask" })
        assert.equals(2, #result.sections)
        assert.equals("legacy-map", result.sections[1].source)
        assert.equals('collaboration-mode map name "Missing" matches no heading', result.notices[2])
    end)
    it("reports non-ASCII map entries without guessing and keeps Unicode tags usable", function()
        local result = scan({ "---", "collaboration-mode: {chat: [CAFÉ]}", "---", "@@chat@@", "# café", "1. ask" })
        assert.equals(1, #result.sections)
        assert.equals("tag", result.sections[1].source)
        assert.is_false(result.sections[1].legacy)
        assert.equals(2, #result.notices)
        assert.equals("legacy chat map entry not matched; use @@chat@@", result.notices[2])
    end)
    it("retains tags under scalar chat and notices retired keys exactly", function()
        local result = scan({ "---", "collaboration-mode: chat", "presentation: inline", "processing-mode: patch", "---", "@@chat@@", "# Notes", "- ask" })
        assert.same({ 6 }, result.tags)
        assert.same({ { heading = 0, finish = 8, source = "legacy-scalar", legacy = true } }, result.sections)
        assert.equals("retired keys ignored: presentation, processing-mode", result.notices[2])
    end)
    it("degrades unsupported metadata to a notice only for a closed leading fence", function()
        local result = scan({ "---", "[bad", "---", "@@chat@@", "# Notes" })
        assert.equals("frontmatter could not be read, so any legacy mode keys in it were not read", result.notices[1])
        assert.equals(1, #result.sections)
        assert.same({}, scan({ "---", "not a fence" }).notices)
    end)
    it("notices closed CR or spaced fences and document markers without losing body headings", function()
        for _, lines in ipairs({
            { "---\r", "collaboration-mode: chat\r", "---\r", "# Body" },
            { " --- ", "collaboration-mode: chat", "---", "# Body" },
            { "---", "...", "collaboration-mode: chat", "---", "# Body" },
        }) do
            local result = scan(lines)
            assert.equals("frontmatter could not be read, so any legacy mode keys in it were not read", result.notices[1])
            assert.equals(0, #result.sections)
        end
    end)
    it("combines tag and immediate legacy comment evidence", function()
        local result = scan({ "@@chat@@", "# Notes", "<!-- collaboration-mode: chat; presentation: inline -->", "- ask" })
        assert.same({ 3 }, result.legacy_comments)
        assert.is_true(result.sections[1].legacy)
        assert.equals("tag", result.sections[1].source)
        assert.equals("<!-- collaboration-mode: chat; presentation: inline --> at line 3 is a legacy key; read as @@chat@@", result.notices[1])
    end)
    it("reads scalar chat map names and empty legacy values without failing a round", function()
        local result = scan({ "---", "collaboration-mode: {chat: Notes}", "---", "# Notes", "- ask" })
        assert.equals("legacy-map", result.sections[1] and result.sections[1].source)
        result = scan({ "---", "collaboration-mode:", "---", "# Notes" })
        assert.equals("collaboration-mode is empty or malformed; ignored", result.notices[1])
    end)
    it("uses innermost grammar and preserves item coordinates and blank-prose boundaries", function()
        local lines = { "# Outer", "<!-- collaboration-mode: chat -->", "- old", "", "prose", "@@chat@@", "## Inner", "- ordinary", "1. ask 🤖[question]", "   continuation", "", "prose", "2. other", "   → [answer](x)", "   follow-up" }
        local result = scan(lines)
        local items = policy.items(lines, result)
        assert.equals(3, #items)
        assert.equals(3, items[1].line)
        assert.equals(3, items[1].finish)
        assert.equals(9, items[2].line)
        assert.equals(10, items[2].finish)
        assert.equals(13, items[3].line)
        assert.is_true(items[3].answered)
        assert.equals(7, result.row_section[9].heading)
    end)
end)

describe("chat policy work", function()
    it("bounds repeated normalized names and duplicate headings", function()
        local function work(count)
            local names, lines, headings = {}, { "---", "", "---" }, {}
            for _ = 1, count do names[#names + 1] = "Notes" end
            lines[2] = "collaboration-mode: {chat: [" .. table.concat(names, ",") .. "]}"
            for _ = 1, count do
                lines[#lines + 1] = "# Notes"
                headings[#headings + 1] = { line = #lines, finish = #lines, level = 1, name = "Notes", kind = "atx" }
            end
            local running = jit.status()
            jit.off()
            jit.flush()
            local ticks = 0
            debug.sethook(function() ticks = ticks + 1 end, "", 1)
            local ok, result = pcall(policy.scan, lines, { headings = headings, body_start = 4, code_lines = {} })
            debug.sethook()
            if running then jit.on() end
            assert.is_true(ok)
            assert.equals(count, #result.sections)
            return ticks
        end
        local small, large = work(512), work(1024)
        assert.is_true(large < small * 2.5 + 100, ("VM work grew from %d to %d"):format(small, large))
    end)
end)
