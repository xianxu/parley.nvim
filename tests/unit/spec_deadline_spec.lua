-- Clock values are synthetic: these tests never sleep or start a subprocess.
describe("spec deadline policy", function()
    local Policy
    local function load_policy()
        local ok, module = pcall(require, "tests.helpers.spec_deadline")
        assert.is_true(ok, tostring(module))
        return module
    end
    local function progress(state, sequence, now)
        return Policy.transition(state, {kind="progress",sequence=sequence,now_ms=now})
    end
    local function tick(state, now)
        return Policy.transition(state, {kind="tick",now_ms=now})
    end
    local function status(state)
        return Policy.snapshot(state).status
    end

    it("retains bounded machine-load scaling", function()
        Policy=load_policy()
        for _, case in ipairs({{0,12,1},{12,12,1},{30,12,2.5},{105,12,4},{5,0,4}}) do
            assert.equals(case[3], Policy.load_factor(case[1],case[2]))
        end
    end)
    it("starts one inactivity budget and an unscaled four-base absolute ceiling", function()
        Policy=load_policy()
        local state=Policy.new(50,30,12,1000)
        assert.same({status="running",completed=false,idle_ms=125,absolute_ms=200,
            started_at=1000,last_progress_at=1000,observed_at=1000,sequence=0}, Policy.snapshot(state))
        assert.equals(200,Policy.snapshot(Policy.new(50,105,12,0)).absolute_ms)
    end)
    it("allows bounded sequential work beyond the former whole-file deadline", function()
        Policy=load_policy()
        local state=Policy.new(50,0,12,0)
        state=progress(state,1,40)
        state=progress(state,2,80)
        assert.equals("running",status(state))
        state=Policy.transition(state,{kind="exit",now_ms=90})
        assert.equals("completed",status(state))
        assert.is_true(Policy.snapshot(state).completed)
    end)
    it("applies inactivity to bootstrap, a running case and teardown", function()
        Policy=load_policy()
        local bootstrap=Policy.new(50,0,12,0)
        assert.equals("stalled",status(tick(bootstrap,50)))
        local between=progress(bootstrap,1,40)
        assert.equals("running",status(tick(between,89)))
        assert.equals("stalled",status(tick(between,90)))
        assert.equals("stalled",status(Policy.transition(between,{kind="exit",now_ms=90})))
    end)
    it("checks expiry before progress and gives the absolute ceiling precedence", function()
        Policy=load_policy()
        local state=Policy.new(50,0,12,0)
        assert.equals("stalled",status(progress(state,1,50)))
        assert.equals("stalled",status(Policy.transition(state,{kind="exit",now_ms=50})))
        for sequence=1,4 do state=progress(state,sequence,sequence*40) end
        assert.equals("running",status(state))
        assert.equals("absolute-expired",status(progress(state,5,200)))
        assert.equals("absolute-expired",status(Policy.transition(state,{kind="exit",now_ms=200})))
        assert.equals("absolute-expired",status(tick(Policy.new(50,0,12,0),200)))
    end)
    it("does not double-scale the absolute ceiling under contention", function()
        Policy=load_policy()
        local state=Policy.new(50,105,12,0)
        assert.equals(200,Policy.snapshot(state).idle_ms)
        state=progress(state,1,199)
        assert.equals("running",status(state))
        assert.equals("absolute-expired",status(tick(state,200)))
    end)
    it("only exact-next positive integer sequences refresh inactivity", function()
        Policy=load_policy()
        for _, invalid in ipairs({0,-1,1,3,2.5,"2",false,{},math.huge,0/0}) do
            local state=progress(Policy.new(50,0,12,0),1,40)
            state=progress(state,invalid,80)
            assert.equals(40,Policy.snapshot(state).last_progress_at)
            assert.equals(1,Policy.snapshot(state).sequence)
            assert.equals("stalled",status(tick(state,90)))
        end
        local state=progress(Policy.new(50,0,12,0),1,40)
        state=Policy.transition(state,{kind="progress",now_ms=80})
        assert.equals("stalled",status(tick(state,90)))
    end)
    it("rejects stale frames without accepting an old clock as fresh work", function()
        Policy=load_policy()
        local state=progress(Policy.new(50,0,12,0),1,40)
        state=tick(state,70)
        state=progress(state,2,60)
        assert.equals(40,Policy.snapshot(state).last_progress_at)
        assert.equals(1,Policy.snapshot(state).sequence)
        state=progress(state,2,70)
        assert.equals(70,Policy.snapshot(state).last_progress_at)
        state=progress(state,3,70)
        assert.equals(3,Policy.snapshot(state).sequence)
    end)
    it("ignores malformed clocks and unrecognized events without refreshing", function()
        Policy=load_policy()
        for _, invalid in ipairs({"80",false,{},math.huge,-math.huge,0/0}) do
            local state=progress(Policy.new(50,0,12,0),1,40)
            state=progress(state,2,invalid)
            assert.equals(40,Policy.snapshot(state).last_progress_at)
            assert.equals(40,Policy.snapshot(state).observed_at)
        end
        local state=progress(Policy.new(50,0,12,0),1,40)
        state=Policy.transition(state,{kind="stdout",sequence=2,now_ms=80})
        assert.equals("stalled",status(tick(state,90)))
    end)
    it("never revives any terminal outcome", function()
        Policy=load_policy()
        local initial=Policy.new(50,0,12,0)
        for _, terminal in ipairs({tick(initial,50),tick(initial,200),Policy.transition(initial,{kind="exit",now_ms=40})}) do
            local before=Policy.snapshot(terminal)
            for _, event in ipairs({{kind="progress",sequence=1,now_ms=41},{kind="tick",now_ms=999},{kind="exit",now_ms=42}}) do
                terminal=Policy.transition(terminal,event)
                assert.same(before,Policy.snapshot(terminal))
            end
        end
    end)
    it("keeps predecessor state and detached observations immutable", function()
        Policy=load_policy()
        local original=Policy.new(50,0,12,0)
        local observed=Policy.snapshot(original)
        local next_state=progress(original,1,40)
        assert.is_not.equals(original,next_state)
        assert.equals(0,Policy.snapshot(original).last_progress_at)
        observed.status, observed.idle_ms="completed",9999
        original.status="completed"
        assert.equals("running",status(original))
        assert.equals(50,Policy.snapshot(original).idle_ms)
        assert.equals(40,Policy.snapshot(next_state).last_progress_at)
    end)
end)
