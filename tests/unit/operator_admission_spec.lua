local admission
local function acquire(model, fields)
    fields = fields or {}
    fields.type = 'acquire'
    fields.token = fields.token or 'turn-1'
    return model.dispatch(fields)
end
local function confirmed(model, effect, proof)
    return model.dispatch({ type = 'acquired', witness = effect.witness, proof = proof or 'owned proof' })
end
local function failed(model, effect, kind)
    model.dispatch({ type = kind, witness = effect.witness, message = kind .. ' message' })
end
local function release(model)
    local effect = model.dispatch({ type = 'release' })
    assert.equals('release', effect.kind)
    model.dispatch({ type = 'released', witness = effect.witness })
end

describe('pure operator admission history', function()
    before_each(function()
        local ok, module = pcall(require, 'parley.operator_admission')
        admission = ok and module or { new = function()
            assert.is_true(false, 'operator admission owner is missing')
        end }
    end)

    it('preserves the original edit through unavailable, save, refusal and confirmed retry', function()
        local model = admission.new()
        local first = acquire(model, { baseline = 'original', content = 'original', clean = true })
        assert.equals('acquiring', model.snapshot().phase)
        failed(model, first, 'unavailable')
        model.dispatch({ type = 'observe', content = 'saved edit' })
        local second = acquire(model, { baseline = 'saved edit', content = 'saved edit', clean = true, token = 'replacement' })
        assert.equals('turn-1', second.token)
        failed(model, second, 'refused')
        model.dispatch({ type = 'observe', content = 'saved edit' })
        local third = acquire(model, { baseline = 'saved edit', content = 'saved edit', clean = true })
        assert.is_nil(confirmed(model, third))
        local state = model.snapshot()
        assert.equals('held', state.phase)
        assert.equals('original', state.baseline)
        assert.is_true(state.unconfirmed_edit)
        assert.equals('owned proof', state.owned_lock)
        assert.equals('turn-1', state.acquire_token)
    end)

    it('freshens only a clean round without outstanding edits', function()
        local model = admission.new()
        local first = acquire(model, { baseline = 'old', content = 'old', clean = true })
        local freshen = confirmed(model, first)
        assert.equals('freshen', freshen.kind)
        assert.equals('freshening', model.snapshot().phase)
        model.dispatch({ type = 'observe', content = 'fresh' })
        model.dispatch({ type = 'freshened', witness = freshen.witness, content = 'fresh', clean = true })
        assert.equals('fresh', model.snapshot().baseline)
        assert.equals('held', model.snapshot().phase)
        release(model)
        assert.equals('idle', model.snapshot().phase)
        assert.is_nil(model.snapshot().baseline)
        assert.is_nil(model.snapshot().acquire_token)
    end)

    it('keeps dirty unknown baselines unknown through every retry', function()
        local model = admission.new()
        local effect = acquire(model, { content = 'dirty', clean = false })
        failed(model, effect, 'unavailable')
        effect = acquire(model, { baseline = 'dirty', content = 'dirty', clean = true })
        assert.is_nil(confirmed(model, effect))
        assert.is_nil(model.snapshot().baseline)
        assert.is_true(model.snapshot().unconfirmed_edit)
    end)

    it('uses the previous content as the normal edit baseline', function()
        local model = admission.new()
        local effect = acquire(model, { baseline = 'before edit', content = 'after edit', clean = false })
        confirmed(model, effect)
        assert.equals('before edit', model.snapshot().baseline)
        assert.is_true(model.snapshot().unconfirmed_edit)
    end)

    it('ignores duplicate and stale outcomes across retries and releases', function()
        local model = admission.new()
        local first = acquire(model, { baseline = 'A', content = 'A' })
        failed(model, first, 'unavailable')
        local second = acquire(model, { baseline = 'B', content = 'B' })
        assert.is_nil(confirmed(model, first, 'stale proof'))
        assert.equals('acquiring', model.snapshot().phase)
        confirmed(model, second, 'current proof')
        failed(model, second, 'refused')
        assert.equals('held', model.snapshot().phase)
        local old_release = model.dispatch({ type = 'release' })
        model.dispatch({ type = 'release_failed', witness = old_release.witness, message = 'disk failure' })
        local new_release = model.dispatch({ type = 'release' })
        model.dispatch({ type = 'released', witness = old_release.witness })
        assert.equals('A', model.snapshot().baseline)
        model.dispatch({ type = 'released', witness = new_release.witness })
        assert.is_false(model.snapshot().history)
        assert.is_nil(model.snapshot().owned_lock)
    end)

    it('does not retire any history on observation or failed release', function()
        local model = admission.new()
        local effect = acquire(model, { baseline = 'A', content = 'A' })
        failed(model, effect, 'refused')
        local pending = model.dispatch({ type = 'release' })
        assert.equals('turn-1', pending.token)
        assert.is_nil(pending.proof)
        model.dispatch({ type = 'release_failed', witness = pending.witness })
        model.dispatch({ type = 'observe', content = 'A' })
        assert.equals('refused', model.snapshot().phase)
        assert.equals('A', model.snapshot().baseline)
        assert.equals('refused message', model.snapshot().admission_message)
    end)

    it('restores validated journals and translates only their exact preimage baseline', function()
        local model = admission.new()
        model.dispatch({ type = 'restore', baseline = 'old bytes', proof = 'journal proof', token = 'journal turn' })
        model.dispatch({ type = 'rebase', before = 'unrelated', after = 'wrong' })
        assert.equals('old bytes', model.snapshot().baseline)
        model.dispatch({ type = 'rebase', before = 'old bytes', after = 'rewritten bytes' })
        assert.equals('rewritten bytes', model.snapshot().baseline)
        local _, reason = model.dispatch({ type = 'restore', baseline = 'other', proof = 'foreign' })
        assert.equals('conflicting operator history', reason)
        assert.equals('journal proof', model.snapshot().owned_lock)
        assert.equals('journal turn', model.snapshot().acquire_token)
    end)

    it('adopts legacy proof without replacing an outstanding baseline', function()
        local model = admission.new()
        model.dispatch({ type = 'legacy_adopt', baseline = 'before', content = 'after', proof = 'legacy bytes' })
        model.dispatch({ type = 'legacy_adopt', baseline = 'after', content = 'after', proof = 'legacy bytes' })
        assert.equals('before', model.snapshot().baseline)
        assert.equals('legacy bytes', model.snapshot().owned_lock)
        assert.is_nil(model.snapshot().acquire_token)
        model.dispatch({ type = 'legacy_adopt', baseline = 'after', content = 'after', proof = 'new exact legacy write' })
        assert.equals('before', model.snapshot().baseline)
        assert.equals('new exact legacy write', model.snapshot().owned_lock)
        release(model)
        assert.is_false(model.snapshot().history)
    end)

    it('copies snapshots and operation effects instead of exposing mutable state', function()
        local model = admission.new()
        local effect = acquire(model, { baseline = 'A', content = 'A', clean = true })
        local copy = model.snapshot()
        copy.baseline, copy.acquire_token, copy.phase = 'forged', 'forged', 'idle'
        effect.token = 'forged'
        local freshen = confirmed(model, effect)
        assert.equals('turn-1', model.snapshot().acquire_token)
        failed(model, freshen, 'refused')
        assert.equals('A', model.snapshot().baseline)
        assert.equals('refused', model.snapshot().phase)
    end)
    it('does not freshen away an edit observed while acquisition was pending', function()
        local model = admission.new()
        local effect = acquire(model, { baseline = 'before', content = 'before', clean = true })
        model.dispatch({ type = 'observe', content = 'changed' })
        assert.is_nil(confirmed(model, effect))
        assert.equals('before', model.snapshot().baseline)
    end)

    it('adopts observed legacy history but cannot launder unknown registered history', function()
        local model = admission.new()
        model.dispatch({ type = 'legacy_adopt', content = 'changed', proof = 'legacy' })
        model.dispatch({ type = 'observed', baseline = 'before', content = 'changed' })
        assert.equals('before', model.snapshot().baseline)
        release(model)
        local effect = acquire(model, { content = 'unknown edits' })
        failed(model, effect, 'unavailable')
        model.dispatch({ type = 'observed', baseline = 'unknown edits', content = 'unknown edits' })
        assert.is_nil(model.snapshot().baseline)
        assert.is_true(model.snapshot().unconfirmed_edit)
    end)

    it('does not freshen away a newer content observation supplied with retry', function()
        local model = admission.new()
        local first = acquire(model, { baseline = 'before', content = 'before', clean = true })
        failed(model, first, 'unavailable')
        local second = acquire(model, { baseline = 'changed', content = 'changed', clean = true })
        assert.is_nil(confirmed(model, second))
        assert.equals('before', model.snapshot().baseline)
    end)

    it('reports whether outcomes were consumed after reentrant acquisition supersedes release', function()
        local model = admission.new()
        local first = acquire(model, { baseline = 'A', content = 'A' })
        local _, _, accepted = confirmed(model, first)
        assert.is_true(accepted)
        local old_release = model.dispatch({ type = 'release' })
        local newer = acquire(model, { baseline = 'A', content = 'A' })
        local _, _, stale = model.dispatch({ type = 'released', witness = old_release.witness })
        assert.is_false(stale)
        assert.equals('acquiring', model.snapshot().phase)
        local _, _, acquired = confirmed(model, newer)
        assert.is_true(acquired)
        local current = model.dispatch({ type = 'release' })
        local _, _, released = model.dispatch({ type = 'released', witness = current.witness })
        assert.is_true(released)
        local _, _, duplicate = model.dispatch({ type = 'released', witness = current.witness })
        assert.is_false(duplicate)
    end)

    it('marks freshening and failed outcomes consumed once only', function()
        local model = admission.new()
        local effect = acquire(model, { baseline = 'A', content = 'A', clean = true })
        local freshen, _, acquired = confirmed(model, effect)
        assert.is_true(acquired)
        local _, _, freshened = model.dispatch({ type = 'freshened', witness = freshen.witness,
            content = 'B', clean = true })
        assert.is_true(freshened)
        local _, _, stale = model.dispatch({ type = 'refused', witness = freshen.witness })
        assert.is_false(stale)
        local pending = model.dispatch({ type = 'release' })
        local _, _, failed_release = model.dispatch({ type = 'release_failed', witness = pending.witness })
        assert.is_true(failed_release)
        local _, _, duplicate = model.dispatch({ type = 'release_failed', witness = pending.witness })
        assert.is_false(duplicate)
    end)

    it('rebases a clean unavailable reload before confirmed retry without retiring the turn', function()
        local model = admission.new()
        local first = acquire(model, { baseline = 'old', content = 'old', clean = true })
        failed(model, first, 'unavailable')
        model.dispatch({ type = 'reload', before = 'old', after = 'external', clean = true })
        local state = model.snapshot()
        assert.equals('external', state.baseline)
        assert.equals('external', state.content)
        assert.equals('unconfirmed', state.phase)
        assert.equals('turn-1', state.acquire_token)
        assert.is_true(state.history)
        local retry = acquire(model, { baseline = 'external', content = 'external', clean = true })
        assert.equals('freshen', confirmed(model, retry).kind)
    end)

    it('cannot rebase outstanding saved edits through a clean disk reload', function()
        local model = admission.new()
        local first = acquire(model, { baseline = 'original', content = 'original', clean = true })
        failed(model, first, 'unavailable')
        model.dispatch({ type = 'observe', content = 'saved edit' })
        model.dispatch({ type = 'reload', before = 'saved edit', after = 'external', clean = true })
        assert.equals('original', model.snapshot().baseline)
        assert.equals('external', model.snapshot().content)
        assert.is_true(model.snapshot().unconfirmed_edit)
    end)

    it('does not advance a dirty, unknown or mismatched reload baseline', function()
        for _, scenario in ipairs({
            { baseline = 'old', content = 'old', before = 'old', clean = false },
            { content = 'unknown', before = 'unknown', clean = true },
            { baseline = 'old', content = 'old', before = 'other', clean = true },
            { baseline = 'old', content = 'changed', before = 'old', clean = true },
        }) do
            local model = admission.new()
            local first = acquire(model, { baseline = scenario.baseline, content = scenario.content })
            failed(model, first, 'unavailable')
            model.dispatch({ type = 'reload', before = scenario.before, after = 'external', clean = scenario.clean })
            assert.equals(scenario.baseline, model.snapshot().baseline)
            assert.equals('external', model.snapshot().content)
            assert.equals('turn-1', model.snapshot().acquire_token)
        end
    end)

    it('still freshens after acknowledgment when a clean reload arrived during acquisition', function()
        local model = admission.new()
        local pending = acquire(model, { baseline = 'old', content = 'old', clean = true })
        model.dispatch({ type = 'reload', before = 'old', after = 'external', clean = true })
        assert.equals('acquiring', model.snapshot().phase)
        assert.equals('external', model.snapshot().baseline)
        local freshen = confirmed(model, pending)
        assert.equals('freshen', freshen.kind)
        model.dispatch({ type = 'freshened', witness = freshen.witness, content = 'freshest', clean = true })
        assert.equals('freshest', model.snapshot().baseline)
    end)

end)
