local Result=require('parley.tools.result_evidence')
local NOTICE='[Tool result incomplete]\n'
describe('bounded truthful result evidence',function()
    it('retains complete results byte for byte',function()
        assert.equals('complete',Result.publish({content='complete'},8).content)
    end)
    it('reserves visible evidence within ordinary result budgets',function()
        local result=Result.publish({content=string.rep('x',200)},64)
        assert.equals(64,#result.content);assert.is_true(result.truncated)
        assert.equals(NOTICE,result.content:sub(1,#NOTICE))
    end)
    it('uses only fixed metadata when a tiny or zero body budget cannot fit a notice',function()
        for _,budget in ipairs({0,1,8})do
            assert.equals(NOTICE,Result.publish({content='omitted source',truncated=true},budget).content)
        end
    end)
    it('does not duplicate notices across repeated normalization and serialization',function()
        local once=Result.publish({content=string.rep('x',200)},64)
        assert.same(once,Result.publish(once,64))
        local rendered=require('parley.tools.serialize').render_result(once)
        local _,count=rendered:gsub('%[Tool result incomplete%]','')
        assert.equals(1,count)
    end)
    it('preserves upstream loss even when later content fits',function()
        assert.equals(NOTICE..'partial',Result.publish({content='partial',truncated=true},128).content)
    end)
    it('keeps reconciliation evidence visible beside omission even at zero capacity',function()
        local result=Result.publish({content='lost',reconciliation_required=true},0)
        assert.equals(NOTICE..'[Disk updated; buffer reconciliation required]\n',result.content)
        assert.equals(Result.notice_bytes,#result.content)
        assert.same(result,Result.publish(result,0))
    end)    it('keeps deliberate paging and an upstream omission visible together',function()
        local Dispatch=require('parley.tools.dispatcher')
        local paged=Dispatch.page_lines('one\ntwo\nthree',2,1)
        local result=Result.publish({content=paged,truncated=true},256)
        assert.truthy(result.content:find('lines 2-2 of 3',1,true))
        assert.equals(NOTICE,result.content:sub(1,#NOTICE))
    end)

end)
