local parley = require("parley")
local api = vim.api

local function keys(text)
    api.nvim_feedkeys(api.nvim_replace_termcodes(text, true, false, true), "xt", false)
end

local function path()
    return vim.fn.resolve(api.nvim_buf_get_name(0))
end

local function cursor(row, col)
    api.nvim_win_set_cursor(0, { row, col or 0 })
end

describe("per-window file Back (#333)", function()
    local root, files, hidden
    local function open(name)
        vim.cmd("edit " .. vim.fn.fnameescape(files[name]))
        if name ~= "source" then parley.setup_markdown_keymaps(api.nvim_get_current_buf()) end
    end
    local function back()
        assert.is_function(parley.cmd.FileBack)
        return parley.cmd.FileBack()
    end

    before_each(function()
        keys("<Esc>")
        vim.cmd("silent! only")
        vim.cmd("silent! %bwipeout!")
        hidden = vim.o.hidden
        vim.o.hidden = true
        root = vim.fn.resolve(vim.fn.tempname())
        vim.fn.mkdir(root, "p")
        files = {}
        for _, name in ipairs({ "session", "answer", "side", "other", "source" }) do
            files[name] = root .. "/" .. name .. (name == "source" and ".lua" or ".md")
            vim.fn.writefile({ "# " .. name, "one two three", "three four five", "last line" }, files[name])
        end
        parley.setup({ chat_dir = root .. "/chats", state_dir = root .. "/state", providers = {}, api_keys = {} })
        open("session")
    end)

    after_each(function()
        keys("<Esc>")
        vim.cmd("silent! only")
        vim.cmd("silent! %bwipeout!")
        vim.o.hidden = hidden
        vim.fn.delete(root, "rf")
    end)

    it("follows Alt+o down session/answer/side links and backs up file by file", function()
        vim.fn.mkdir(root .. "/.git", "p")
        vim.fn.writefile({ "# Session", "", "[answer](" .. files.answer .. ")", "root text" }, files.session)
        vim.fn.writefile({ "# Answer", "", "[side](" .. files.side .. ")", "answer text" }, files.answer)
        vim.cmd("edit!")
        cursor(3, 2)
        keys("<M-o>")
        assert.equals(files.answer, path())
        -- The winbar names the file, never the trail that reached it (#391).
        assert.truthy(vim.wo.winbar:find(" answer%=", 1, true))
        assert.is_nil(vim.wo.winbar:find("session", 1, true))
        cursor(3, 2)
        keys("<M-o>")
        assert.equals(files.side, path())
        assert.truthy(vim.wo.winbar:find(" side%=", 1, true))
        keys("GggG")
        keys("<M-O>")
        assert.equals(files.answer, path())
        assert.same({ 3, 2 }, api.nvim_win_get_cursor(0))
        keys("<M-O>")
        assert.equals(files.session, path())
        assert.same({ 3, 2 }, api.nvim_win_get_cursor(0))
        assert.truthy(vim.wo.winbar:find(" session%=", 1, true))
        assert.is_nil(vim.wo.winbar:find("›", 1, true))
        -- A nested file shows its repo-relative directories as segments.
        local nested = root .. "/notes/2026/2026-10-18-plan.md"
        vim.fn.mkdir(vim.fs.dirname(nested), "p")
        vim.fn.writefile({ "# plan" }, nested)
        vim.cmd("edit " .. vim.fn.fnameescape(nested))
        assert.truthy(vim.wo.winbar:find(" notes › 2026 › plan%=", 1, true))
    end)

    it("shows a side doc's tree path, not the trail that reached it, and keeps Back (#391)", function()
        local tree = {}
        local function doc(name, rel, front, body)
            tree[name] = root .. "/" .. rel
            vim.fn.mkdir(vim.fs.dirname(tree[name]), "p")
            local lines = { "---" }
            vim.list_extend(lines, front)
            vim.list_extend(lines, { "---", "# " .. name })
            vim.list_extend(lines, body or {})
            vim.fn.writefile(lines, tree[name])
        end
        doc("A", "A.md", { "discussions:", "  - doc: A.side/B1.md" })
        doc("B1", "A.side/B1.md", { "parent: ../A.md", "discussions:", "  - doc: B1.side/C1.md" })
        doc("B2", "A.side/B2.md", { "parent: ../A.md" })
        doc("C1", "A.side/B1.side/C1.md", { "parent: ../B1.md" })
        doc("C2", "A.side/B2.side/C2.md", { "parent: \"../B2.md\"" }, { "[c1](" .. root .. "/A.side/B1.side/C1.md)" })
        vim.cmd("edit " .. vim.fn.fnameescape(tree.C2))
        parley.setup_markdown_keymaps(api.nvim_get_current_buf())
        assert.truthy(vim.wo.winbar:find("A › B2 › C2", 1, true))
        cursor(5, 2)
        keys("<M-o>")
        assert.equals(tree.C1, path())
        assert.truthy(vim.wo.winbar:find("A › B1 › C1", 1, true))
        assert.is_nil(vim.wo.winbar:find("C2", 1, true))
        assert.same({ tree.C2, tree.C1 }, require("parley.file_history").snapshot(0).paths)
        keys("<M-O>")
        assert.equals(tree.C2, path())
        assert.truthy(vim.wo.winbar:find("A › B2 › C2", 1, true))

        -- An edited parent (seen on re-entry) that no longer exists ends with a marker.
        local c1 = vim.fn.bufnr(tree.C1)
        api.nvim_buf_set_lines(c1, 1, 2, false, { "parent: ../gone.md" })
        vim.cmd("buffer " .. c1)
        assert.truthy(vim.wo.winbar:find("? › C1", 1, true))
    end)

    it("exports detached trails for real Alt+o and restores native roots on Back", function()
        local history = require("parley.file_history")
        vim.fn.writefile({ "[answer](" .. files.answer .. ")" }, files.session)
        vim.fn.writefile({ "[side](" .. files.side .. ")" }, files.answer)
        vim.cmd("edit!")
        keys("<M-o>")
        keys("<M-o>")
        assert.same({ files.session, files.answer, files.side }, history.snapshot(0).paths)
        local exported = history.snapshot(0)
        exported.paths[1] = files.other
        assert.equals(files.session, history.snapshot(0).paths[1])
        keys("<M-O>")
        assert.same({ files.session, files.answer }, history.snapshot(0).paths)
        open("other")
        assert.same({ files.other }, history.snapshot(0).paths)
        assert.is_true(back())
        assert.same({ files.session, files.answer }, history.snapshot(0).paths)
    end)

    it("rebuilds surviving ancestors from JSON without navigating or moving the leaf cursor", function()
        local history = require("parley.file_history")
        open("side")
        cursor(3, 2)
        local value = vim.json.decode(vim.json.encode({ version = 1,
            paths = { files.session, files.answer, files.side }, omitted = 0 }))
        vim.fn.delete(files.answer)
        assert.is_true(history.restore(0, value))
        assert.equals(files.side, path())
        assert.same({ 3, 2 }, api.nvim_win_get_cursor(0))
        assert.same({ files.session, files.side }, history.snapshot(0).paths)
        value.paths[1] = files.other
        keys("<M-O>")
        assert.equals(files.session, path())
        assert.same({ 1, 0 }, api.nvim_win_get_cursor(0))
    end)

    it("rejects mismatched and uncertain restore inputs before changing the current trail", function()
        local history = require("parley.file_history")
        local before = history.snapshot(0)
        local ok, reason = history.restore(0, { version = 1, paths = { files.answer }, omitted = 0 })
        assert.is_false(ok)
        assert.is_string(reason)
        assert.same(before, history.snapshot(0))
        local uv, stat = vim.uv or vim.loop, (vim.uv or vim.loop).fs_stat
        uv.fs_stat = function(name, ...)
            if name == files.answer then return nil, "EACCES: denied", "EACCES" end
            return stat(name, ...)
        end
        local called, accepted, problem = pcall(history.restore, 0,
            { version = 1, paths = { files.answer, files.session }, omitted = 0 })
        uv.fs_stat = stat
        assert.is_true(called)
        assert.is_false(accepted)
        assert.is_string(problem)
        assert.same(before, history.snapshot(0))
    end)

    it("reconstructs ancestry in an existing destination window while preserving the origin", function()
        local history = require("parley.file_history")
        vim.fn.writefile({ "[answer](" .. files.answer .. ")" }, files.session)
        vim.cmd("edit!")
        local origin = api.nvim_get_current_win()
        vim.cmd("vsplit " .. vim.fn.fnameescape(files.answer))
        local destination = api.nvim_get_current_win()
        api.nvim_set_current_win(origin)
        keys("<M-o>")
        assert.equals(destination, api.nvim_get_current_win())
        assert.same({ files.session, files.answer }, history.snapshot(destination).paths)
        assert.same({ files.session }, history.snapshot(origin).paths)
        keys("<M-O>")
        assert.equals(files.session, path())
    end)

    it("refuses stale origins and never arms an unrelated future visit after an error", function()
        local history = require("parley.file_history")
        local token = history.origin(0)
        open("answer")
        local invoked = false
        local ok = history.follow(token, function() invoked = true end)
        assert.is_false(ok)
        assert.is_false(invoked)
        local fresh = history.origin(0)
        assert.has_error(function() history.follow(fresh, function() error("failed open") end) end)
        open("side")
        assert.same({ files.side }, history.snapshot(0).paths)
    end)

    it("keeps a redirected opener as an ordinary root rather than the intended link", function()
        local history = require("parley.file_history")
        local token = history.origin(0)
        local accepted = history.follow(token, function() open("other") end, files.answer)
        assert.is_false(accepted)
        assert.same({ files.other }, history.snapshot(0).paths)
    end)

    it("restores a leaf-only root when every ancestor was deleted", function()
        local history = require("parley.file_history")
        open("side")
        vim.fn.delete(files.session)
        vim.fn.delete(files.answer)
        assert.is_true(history.restore(0, { version = 1,
            paths = { files.session, files.answer, files.side }, omitted = 2 }))
        assert.same({ version = 1, paths = { files.side }, omitted = 0 }, history.snapshot(0))
    end)

    it("copies a native split's followed trail and diverges on an ordinary visit", function()
        local history = require("parley.file_history")
        vim.fn.writefile({ "[answer](" .. files.answer .. ")" }, files.session)
        vim.cmd("edit!")
        keys("<M-o>")
        local parent = api.nvim_get_current_win()
        vim.cmd("vsplit")
        assert.same({ files.session, files.answer }, history.snapshot(0).paths)
        open("other")
        assert.same({ files.other }, history.snapshot(0).paths)
        assert.same({ files.session, files.answer }, history.snapshot(parent).paths)
    end)

    it("still opens an ordinary file when the origin cannot supply a trail", function()
        local history = require("parley.file_history")
        vim.cmd("enew")
        local token = history.origin(0)
        assert.is_nil(token)
        history.follow(token, function() open("answer") end)
        assert.equals(files.answer, path())
        assert.same({ files.answer }, history.snapshot(0).paths)
    end)

    it("returns a reason when a named file cannot be represented by a snapshot", function()
        local history = require("parley.file_history")
        vim.cmd("enew")
        api.nvim_buf_set_name(0, root .. "/unsupported\nname.md")
        local value, reason = history.snapshot(0)
        assert.is_nil(value)
        assert.equals("string", type(reason))
    end)

    it("projects a detached cached trail without observing or resolving files on repaint", function()
        local history = require("parley.file_history")
        local expected = history.snapshot(0)
        local resolve = vim.fn.resolve
        local calls = 0
        vim.fn.resolve = function(...)
            calls = calls + 1
            return resolve(...)
        end
        local ok, value = pcall(function() return history.peek(0) end)
        vim.fn.resolve = resolve
        assert.is_true(ok)
        assert.same(expected, value)
        assert.equals(0, calls)
        value.paths[1] = files.other
        assert.same(expected, history.peek(0))
    end)

    it("keeps the latest repeated-path departure cursor when a bounded trail drops interior visits", function()
        local history = require("parley.file_history")
        local paths = {}
        for i = 1, 200 do paths[i] = files.session end
        cursor(4, 3)
        assert.is_true(history.restore(0, { version = 1, paths = paths, omitted = 0 }))
        assert.is_true(history.follow(history.origin(0), function() open("answer") end, files.answer))
        assert.equals(200, #history.snapshot(0).paths)
        assert.equals(1, history.snapshot(0).omitted)
        assert.is_true(back())
        assert.equals(files.session, path())
        assert.same({ 4, 3 }, api.nvim_win_get_cursor(0))
    end)

    for _, form in ipairs({ "at", "branch", "inline-branch", "src", "gf" }) do
        it("commits the successful " .. form .. " Alt+o landing to the trail", function()
            local target = files.answer
            local line = form == "at" and ("@@" .. target .. "@@")
                or form == "branch" and ("🌿: " .. target .. ": Answer")
                or form == "inline-branch" and ("[🌿:Answer](" .. target .. ")")
                or form == "src" and "[Answer](src:/answer.md)" or target
            parley.config.src_root = root
            vim.fn.writefile({ line }, files.session)
            vim.cmd("edit!")
            cursor(1)
            keys("<M-o>")
            assert.equals(target, path())
            assert.same({ files.session, target }, require("parley.file_history").snapshot(0).paths)
        end)
    end

    it("records native gf, edit and picker-style buffer switches, including source files", function()
        vim.fn.writefile({ files.answer, "root" }, files.session)
        vim.cmd("edit!")
        cursor(1)
        vim.cmd("normal! gf")
        assert.equals(files.answer, path())
        cursor(2, 3)
        open("source")
        cursor(3, 4)
        api.nvim_win_set_buf(0, vim.fn.bufadd(files.side))
        assert.is_true(back())
        assert.equals(files.source, path())
        assert.same({ 3, 4 }, api.nvim_win_get_cursor(0))
        assert.is_true(back())
        assert.equals(files.answer, path())
        assert.same({ 2, 3 }, api.nvim_win_get_cursor(0))
        assert.is_true(back())
        assert.equals(files.session, path())
    end)

    it("skips a deleted exact filename despite a loaded backup with a matching name", function()
        open("answer")
        local answer = api.nvim_get_current_buf()
        open("side")
        api.nvim_buf_delete(answer, { force = true })
        vim.fn.delete(files.answer)
        local backup = files.answer .. ".bak"
        vim.fn.writefile({ "backup" }, backup)
        vim.fn.bufload(vim.fn.bufadd(backup))
        assert.is_true(back())
        assert.equals(files.session, path())
    end)

    it("collapses same-file jumps and truncates the forward tail after a new visit", function()
        cursor(2, 1)
        open("answer")
        keys("GggG")
        open("side")
        assert.is_true(back())
        assert.same({ 4, 0 }, api.nvim_win_get_cursor(0))
        open("other")
        assert.is_true(back())
        assert.equals(files.answer, path())
        assert.is_true(back())
        assert.equals(files.session, path())
        assert.same({ 2, 1 }, api.nvim_win_get_cursor(0))
        assert.is_false(back())
        assert.equals(files.session, path())
    end)

    it("copies the parent's history into a split and keeps later cursors and visits independent", function()
        cursor(2, 2)
        open("answer")
        cursor(4, 3)
        local parent = api.nvim_get_current_win()
        vim.cmd("vsplit")
        local child = api.nvim_get_current_win()
        cursor(3, 1)
        open("side")
        assert.is_true(back())
        assert.equals(child, api.nvim_get_current_win())
        assert.equals(files.answer, path())
        assert.same({ 3, 1 }, api.nvim_win_get_cursor(0))
        assert.is_true(back())
        assert.equals(files.session, path())
        api.nvim_set_current_win(parent)
        assert.equals(files.answer, path())
        assert.same({ 4, 3 }, api.nvim_win_get_cursor(0))
        assert.is_true(back())
        assert.equals(files.session, path())
        assert.same({ 2, 2 }, api.nvim_win_get_cursor(0))
        api.nvim_set_current_win(child)
        assert.is_false(back())
    end)

    it("inherits history when the split opens a different file immediately", function()
        open("answer")
        vim.cmd("split " .. vim.fn.fnameescape(files.side))
        assert.is_true(back())
        assert.equals(files.answer, path())
        assert.is_true(back())
        assert.equals(files.session, path())
    end)

    it("starts an inactive API split fresh even when its requested parent is focused", function()
        open("answer")
        local parent = api.nvim_get_current_win()
        vim.cmd("vsplit")
        open("side")
        api.nvim_set_current_win(parent)
        local child = api.nvim_open_win(vim.fn.bufadd(files.other), false, { split = "right", win = parent })
        assert.equals(parent, api.nvim_get_current_win())
        assert.is_true(back())
        assert.equals(files.session, path())
        api.nvim_set_current_win(child)
        assert.is_false(back())
        assert.equals(files.other, path())
        open("source")
        assert.is_true(back())
        assert.equals(files.other, path())
        assert.is_false(back())
    end)

    it("does not infer API ancestry from identical displayed files and cursors", function()
        open("answer")
        local parent, answer = api.nvim_get_current_win(), api.nvim_get_current_buf()
        vim.cmd("vsplit")
        open("other")
        open("answer")
        local focused = api.nvim_get_current_win()
        local child = api.nvim_open_win(answer, false, { split = "right", win = parent })
        api.nvim_set_current_win(child)
        assert.is_false(back())
        api.nvim_set_current_win(focused)
        vim.cmd("split")
        assert.is_true(back())
        assert.equals(files.other, path())
        api.nvim_set_current_win(parent)
        assert.is_true(back())
        assert.equals(files.session, path())
    end)

    it("records immediate API file entries without retaining the temporary clone", function()
        open("answer")
        local second, third = root .. "/second.lua", root .. "/third.lua"
        vim.fn.writefile({ "second" }, second)
        vim.fn.writefile({ "third" }, third)
        local child = api.nvim_open_win(vim.fn.bufadd(files.source), true, { split = "right", win = 0 })
        vim.cmd("edit " .. vim.fn.fnameescape(second))
        vim.cmd("edit " .. vim.fn.fnameescape(third))
        assert.is_true(back())
        assert.equals(second, path())
        assert.is_true(back())
        assert.equals(files.source, path())
        assert.is_false(back())
        assert.equals(child, api.nvim_get_current_win())
    end)

    it("keeps immediate API Back and native split visits without initialization callbacks", function()
        open("answer")
        api.nvim_open_win(vim.fn.bufadd(files.other), true, { split = "right", win = 0 })
        assert.is_false(back())
        open("source")
        vim.cmd("split " .. vim.fn.fnameescape(files.side))
        assert.is_true(back())
        assert.equals(files.source, path())
        assert.is_true(back())
        assert.equals(files.other, path())
        assert.is_false(back())
    end)

    it("releases an API window before a subsequent native split", function()
        open("answer")
        local parent = api.nvim_get_current_win()
        local child = api.nvim_open_win(vim.fn.bufadd(files.other), false, { split = "right", win = parent })
        api.nvim_win_close(child, true)
        vim.cmd("split")
        assert.is_true(back())
        assert.equals(files.session, path())
        api.nvim_set_current_win(parent)
        assert.equals(files.answer, path())
    end)

    for _, direction in ipairs({ "left", "right", "above", "below" }) do
        for _, enter in ipairs({ false, true }) do
            it("starts fresh for an unfocused API parent: " .. direction .. ", enter=" .. tostring(enter), function()
                open("answer")
                local parent, answer = api.nvim_get_current_win(), api.nvim_get_current_buf()
                vim.cmd("vsplit")
                open("other")
                open("side")
                local focused = api.nvim_get_current_win()
                local child = api.nvim_open_win(answer, enter, { split = direction, win = parent })
                assert.equals(enter and child or focused, api.nvim_get_current_win())
                api.nvim_set_current_win(child)
                assert.is_false(back())
                assert.equals(files.answer, path())
                open("source")
                assert.is_true(back())
                assert.equals(files.answer, path())
                assert.is_false(back())
                api.nvim_set_current_win(parent)
                assert.equals(files.answer, path())
                assert.is_true(back())
                assert.equals(files.session, path())
                api.nvim_set_current_win(focused)
                assert.equals(files.side, path())
                assert.is_true(back())
                assert.equals(files.other, path())
            end)
        end
    end

    it("inherits into a new tab and releases a closed split's navigation state", function()
        open("answer")
        local parent = api.nvim_get_current_win()
        vim.cmd("tab split")
        assert.is_true(back())
        assert.equals(files.session, path())
        vim.cmd("tabclose")
        assert.equals(parent, api.nvim_get_current_win())
        assert.equals(files.answer, path())
        vim.cmd("vsplit")
        local closed = api.nvim_get_current_win()
        open("side")
        vim.cmd("close")
        assert.is_false(api.nvim_win_is_valid(closed))
        vim.cmd("vsplit " .. vim.fn.fnameescape(files.other))
        assert.is_true(back())
        assert.equals(files.answer, path())
        assert.is_true(back())
        assert.equals(files.session, path())
    end)

    it("processes consecutive queued Back keys without recording its own navigation", function()
        open("answer")
        open("side")
        keys("<M-O><M-O>")
        assert.equals(files.session, path())
        assert.is_false(back())
    end)

    it("ignores temporary buffers and floating windows without losing the editing history", function()
        open("answer")
        local answer = api.nvim_get_current_buf()
        vim.cmd("enew")
        vim.bo.buftype = "nofile"
        api.nvim_buf_set_name(0, "scratch")
        local scratch = api.nvim_get_current_buf()
        api.nvim_win_set_buf(0, answer)
        local float = api.nvim_open_win(scratch, true, { relative = "editor", row = 1, col = 1, width = 20, height = 3 })
        assert.is_false(back())
        assert.equals(float, api.nvim_get_current_win())
        api.nvim_win_close(float, true)
        assert.is_true(back())
        assert.equals(files.session, path())
    end)

    it("skips a missing unloaded file, while a loaded deleted file remains reachable", function()
        open("answer")
        local answer = api.nvim_get_current_buf()
        open("side")
        api.nvim_buf_delete(answer, { force = true })
        assert(os.remove(files.answer))
        assert.is_true(back())
        assert.equals(files.session, path())
        open("side")
        assert(os.remove(files.session))
        assert.is_true(back())
        assert.equals(files.session, path())
    end)

    it("keeps unsaved text and the Back target when native switching refuses", function()
        open("answer")
        vim.o.hidden = false
        api.nvim_buf_set_lines(0, 1, 2, false, { "unsaved operator text" })
        assert.is_false(back())
        assert.equals(files.answer, path())
        assert.is_true(vim.bo.modified)
        assert.equals("unsaved operator text", api.nvim_buf_get_lines(0, 1, 2, false)[1])
        vim.cmd("write")
        assert.is_true(back())
        assert.equals(files.session, path())
    end)

    it("clamps an obsolete saved cursor when the target buffer has become shorter", function()
        cursor(4, 6)
        local session = api.nvim_get_current_buf()
        open("answer")
        api.nvim_buf_set_lines(session, 0, -1, false, { "x" })
        assert.is_true(back())
        assert.equals(files.session, path())
        assert.same({ 1, 0 }, api.nvim_win_get_cursor(0))
    end)

    it("preserves Insert mode and queued typing through the actual Alt+Shift+O mapping", function()
        cursor(2, 2)
